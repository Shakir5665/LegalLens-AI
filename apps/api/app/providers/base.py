"""Base abstractions, protocols, and data structures for LLM providers.

In adherence to Decision A:
- Application services depend exclusively on this small provider contract.
- Provider implementations isolate SDK-specific types from application code.
- No multi-provider routing or unnecessary abstraction overhead.
"""

from dataclasses import dataclass
from typing import Protocol, runtime_checkable
from pydantic import BaseModel


@dataclass(frozen=True)
class TokenUsage:
    """Documented token consumption reported by the LLM provider.

    Attributes:
        input_tokens: Tokens consumed by the input prompt (prompt_token_count).
        output_tokens: Visible candidate tokens generated by the model (candidates_token_count).
        thinking_tokens: Internal reasoning/planning tokens generated by reasoning models
                         such as Gemini 2.5 Flash (thoughts_token_count or total - (input + output)).
        cached_tokens: Number of prompt tokens served from cache (cached_content_token_count).
        total_tokens: Total tokens processed by the provider (total_token_count).
    """

    input_tokens: int | None = None
    output_tokens: int | None = None
    thinking_tokens: int | None = None
    cached_tokens: int | None = None
    total_tokens: int | None = None

    @property
    def billable_output_tokens(self) -> int | None:
        """Total output tokens billed at standard output rate (candidates + thinking)."""
        if self.output_tokens is None:
            return None
        return self.output_tokens + (self.thinking_tokens or 0)


@dataclass(frozen=True)
class ProviderResponse:
    """Clean, application-level result returned by an LLM provider."""

    content: str
    usage: TokenUsage
    model: str
    latency_ms: float
    finish_reason: str | None = None


@runtime_checkable
class LLMProvider(Protocol):
    """Protocol defining the lightweight contract for LLM operations.

    Application services interact only with this interface, never directly
    with Google GenAI SDK client objects.
    """

    def generate(
        self,
        prompt: str,
        system_instruction: str | None = None,
        temperature: float | None = None,
    ) -> ProviderResponse:
        """Generate a natural-language text response for the given prompt."""
        ...

    def generate_structured(
        self,
        prompt: str,
        response_schema: type[BaseModel],
        system_instruction: str | None = None,
        temperature: float | None = None,
    ) -> ProviderResponse:
        """Generate a strictly structured JSON response conforming to response_schema."""
        ...
