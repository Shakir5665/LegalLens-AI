"""Pydantic schemas for LLM telemetry, request payloads, and structured outputs."""

from datetime import datetime, timezone
from enum import Enum
from typing import TypeVar
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from app.core.llm_errors import LLMResponseValidationError

T = TypeVar("T", bound=BaseModel)


class LLMCallTelemetry(BaseModel):
    """Structured record of an individual LLM model invocation.

    Observability metadata conforming to Phase 2 boundaries:
    - Captures operational indicators, token counts, and cost estimates.
    - Strictly avoids capturing raw prompt bodies, confidential legal documents,
      or API keys (ADR-014).
    """

    model_config = ConfigDict(frozen=True)

    correlation_id: str = Field(..., description="Request or workflow trace correlation ID")
    model: str = Field(..., description="Provider model identifier (e.g. 'gemini-2.5-flash')")
    operation: str = Field(..., description="Name of the use-case or operation (e.g. 'legal_query_analysis')")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of the model call initiation in UTC",
    )
    duration_ms: float = Field(..., ge=0.0, description="Roundtrip call latency in milliseconds")
    input_tokens: int | None = Field(
        default=None,
        ge=0,
        description="Tokens consumed by the input prompt, or None if unavailable from provider",
    )
    output_tokens: int | None = Field(
        default=None,
        ge=0,
        description="Tokens generated in the model output, or None if unavailable from provider",
    )
    thinking_tokens: int | None = Field(
        default=None,
        ge=0,
        description="Internal reasoning tokens generated by the model (e.g. Gemini 2.5 Flash thinking)",
    )
    cached_tokens: int | None = Field(
        default=None,
        ge=0,
        description="Prompt tokens served from provider cache, or None if unavailable",
    )
    total_tokens: int | None = Field(
        default=None,
        ge=0,
        description="Total tokens consumed, or None if unavailable from provider",
    )
    estimated_cost_usd: float | None = Field(
        default=None,
        ge=0.0,
        description="Estimated API cost in USD based on documented pricing assumptions",
    )
    pricing_assumption: str | None = Field(
        default=None,
        description="Human-readable citation of pricing assumption used for cost calculation",
    )
    retry_count: int = Field(default=0, ge=0, description="Number of retry attempts executed")
    success: bool = Field(..., description="Whether the model call completed successfully")
    error_category: str | None = Field(
        default=None,
        description="Sanitized machine-readable error category if failed (e.g. 'TIMEOUT', 'RATE_LIMIT')",
    )


class PotentialStatute(str, Enum):
    """Broad statutory categories in Sri Lankan Employment Law."""

    INDUSTRIAL_DISPUTES_ACT = "industrial_disputes_act"
    TERMINATION_OF_EMPLOYMENT_WORKMEN_ACT = "termination_of_employment_workmen_act"
    PAYMENT_OF_GRATUITY_ACT = "payment_of_gratuity_act"
    OTHER_OR_UNSPECIFIED = "other_or_unspecified"


class LegalUrgencyLevel(str, Enum):
    """Urgency classification reflecting statutory time limits or procedural deadlines."""

    ROUTINE = "ROUTINE"
    TIME_SENSITIVE = "TIME_SENSITIVE"
    CRITICAL = "CRITICAL"


class LegalQueryAnalysisResult(BaseModel):
    """Structured classification output produced by LLM for an incoming legal query.

    Untrusted model output validated strictly with Pydantic v2.
    Note on Gemini API Compatibility:
    - All fields are explicitly required; Google GenAI SDK disallows 'default' values in response schemas.
    - ConfigDict(frozen=True) ensures immutability without injecting 'additionalProperties'.
    """

    model_config = ConfigDict(frozen=True)

    primary_legal_issue: str = Field(
        ...,
        min_length=5,
        max_length=300,
        description="Concise description of the primary legal issue raised",
    )
    potential_statutes: list[PotentialStatute] = Field(
        ...,
        description="Identified potential Sri Lankan statutory frameworks",
    )
    key_factual_elements: list[str] = Field(
        ...,
        max_length=10,
        description="Key factual elements extracted from user inquiry",
    )
    requires_clarification: bool = Field(
        ...,
        description="Whether essential factual details are missing to determine applicability",
    )
    clarification_questions: list[str] = Field(
        ...,
        description="Specific follow-up questions to ask the user if clarification is needed",
    )
    urgency_assessment: LegalUrgencyLevel = Field(
        ...,
        description="Assessed procedural or statutory urgency",
    )
    statutory_grounding_note: str = Field(
        ...,
        description="Architectural grounding disclaimer (e.g. 'Preliminary query classification only. Not authoritative legal advice.')",
    )


class LegalQueryAnalysisResponse(BaseModel):
    """Domain response container combining validated structured analysis with execution telemetry."""

    model_config = ConfigDict(frozen=True)

    analysis: LegalQueryAnalysisResult
    telemetry: LLMCallTelemetry


def validate_structured_response(content: str, schema: type[T]) -> T:
    """Validate raw LLM-generated JSON string against a target Pydantic schema.

    Strict validation adhering to Decision B:
    - Never silently ignores invalid fields or corrupt data.
    - Translates validation or JSON parsing errors into clean LLMResponseValidationError.

    Args:
        content: The raw JSON string returned by the provider.
        schema: Target Pydantic model class.

    Returns:
        Validated instance of schema.

    Raises:
        LLMResponseValidationError: If content is invalid JSON or violates schema constraints.
    """
    if not content or not content.strip():
        raise LLMResponseValidationError(
            message="LLM provider returned empty response content for structured output.",
            details={"error_type": "empty_content"},
        )

    try:
        return schema.model_validate_json(content)
    except ValidationError as exc:
        errors = exc.errors()
        is_json_invalid = any(err.get("type") == "json_invalid" for err in errors)
        if is_json_invalid:
            json_msg = next((err.get("msg") for err in errors if err.get("type") == "json_invalid"), "Invalid JSON")
            raise LLMResponseValidationError(
                message=f"LLM output could not be parsed as valid JSON: {json_msg}",
                details={"validation_errors": errors},
            ) from exc

        raise LLMResponseValidationError(
            message=f"LLM output failed validation for schema '{schema.__name__}'.",
            details={"validation_errors": errors},
        ) from exc
    except Exception as exc:
        raise LLMResponseValidationError(
            message=f"LLM output could not be parsed as valid JSON: {exc}",
            details={"error_type": exc.__class__.__name__},
        ) from exc

